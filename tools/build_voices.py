import json, sys
sys.path.insert(0, 'tools')
from patchlib import Patch

# ---------- Sampler-Voice: exakt der zuletzt funktionierende Stand ----------
v = Patch()
vin = v.obj("in 1", 0, 1, 30, 20)
vrt = v.obj("route env pos rel gateoff", 2, 5, 30, 60)
vposmsg = v.msg("$1, $2 $3", 160, 95)
vposline = v.obj("line~", 2, 2, 160, 118, otypes=["signal", "bang"])
vplay = v.obj("play~ #1 2", 1, 3, 160, 160, otypes=["signal", "signal", "signal"])
vline = v.obj("line~", 2, 2, 30, 160, otypes=["signal", "bang"])
vunp = v.obj("unpack 0. 0.", 1, 2, 290, 100, otypes=["float", "float"])
vdel = v.obj("delay", 2, 1, 290, 140, otypes=["bang"])
vf = v.obj("f", 2, 1, 290, 175, otypes=["float"])
vpre = v.obj("prepend 0", 1, 1, 290, 210)
vtfb = v.obj("t f b", 1, 2, 420, 100, otypes=["float", "bang"])
vstop = v.msg("stop", 460, 140)
vpre2 = v.obj("prepend 0", 1, 1, 420, 210)
vm1 = v.obj("*~", 2, 1, 160, 260, otypes=["signal"])
vm2 = v.obj("*~", 2, 1, 230, 260, otypes=["signal"])
vo1 = v.obj("out~ 1", 1, 0, 160, 300)
vo2 = v.obj("out~ 2", 1, 0, 230, 300)
v.con(vin, 0, vrt, 0)
v.con(vrt, 0, vline, 0)
v.con(vrt, 1, vposmsg, 0); v.con(vposmsg, 0, vposline, 0); v.con(vposline, 0, vplay, 0)
v.con(vrt, 2, vunp, 0); v.con(vunp, 1, vf, 1); v.con(vunp, 0, vdel, 0); v.con(vdel, 0, vf, 0)
v.con(vf, 0, vpre, 0); v.con(vpre, 0, vline, 0)
v.con(vrt, 3, vtfb, 0); v.con(vtfb, 1, vstop, 0); v.con(vstop, 0, vdel, 0)
v.con(vtfb, 0, vpre2, 0); v.con(vpre2, 0, vline, 0)
v.con(vplay, 0, vm1, 0); v.con(vplay, 1, vm2, 0)
v.con(vline, 0, vm1, 1); v.con(vline, 0, vm2, 1)
v.con(vm1, 0, vo1, 0); v.con(vm2, 0, vo2, 0)
json.dump(v.to_json([100, 100, 640, 400]), open("ytvoice.maxpat", "w"), indent=1, ensure_ascii=False)

# ---------- Warp-Voice: groove~ mit Timestretch, schaltet sich im Leerlauf stumm ----------
w = Patch()
win = w.obj("in 1", 0, 1, 30, 20)
wrt = w.obj("route env wplay rel gateoff", 2, 5, 30, 60, w=200)
wenv = w.obj("line~", 2, 2, 30, 330, otypes=["signal", "bang"])
w.con(win, 0, wrt, 0)
w.con(wrt, 0, wenv, 0)

# CPU sparen: Voice nur rechnen, solange sie spielt
wtp = w.obj("thispoly~", 1, 2, 700, 330, otypes=["int", "int"])
wlb = w.obj("loadbang", 1, 1, 700, 230, otypes=["bang"])
wmute1 = w.msg("mute 1", 700, 290)
wmute0 = w.msg("mute 0", 780, 290)
w.con(wlb, 0, wmute1, 0); w.con(wmute1, 0, wtp, 0); w.con(wmute0, 0, wtp, 0)

# wplay <position ms> <tempo> <tonhöhe>
wtlb = w.obj("t l b b", 1, 3, 200, 100, otypes=["", "bang", "bang"])
wunp = w.obj("unpack 0. 0. 0.", 1, 3, 200, 140, otypes=["float", "float", "float"])
wpitch = w.msg("pitchshift $1", 380, 175)
wsig = w.obj("sig~", 1, 1, 290, 210, otypes=["signal"])
wgroove = w.obj("groove~ #1 2 @timestretch 1 @loop 0", 3, 3, 200, 250, w=240,
                otypes=["signal", "signal", "signal"])
wstop_off = w.msg("stop", 460, 140)
w.con(wrt, 1, wtlb, 0)
w.con(wtlb, 2, wmute0, 0)                    # zuerst DSP einschalten
w.con(wtlb, 1, wstop_off, 0)                 # geplantes Stummschalten abbrechen
w.con(wtlb, 0, wunp, 0)
w.con(wunp, 2, wpitch, 0); w.con(wpitch, 0, wgroove, 0)
w.con(wunp, 1, wsig, 0); w.con(wsig, 0, wgroove, 0)
w.con(wunp, 0, wgroove, 0)

# rel <verzögerung> <releasezeit>  /  gateoff <releasezeit>
wunp2 = w.obj("unpack 0. 0.", 1, 2, 560, 60, otypes=["float", "float"])
wdel = w.obj("delay", 2, 1, 560, 95, otypes=["bang"])
wf = w.obj("f", 2, 1, 560, 125, otypes=["float"])
wtff = w.obj("t f f", 1, 2, 560, 160, otypes=["float", "float"])
wpre = w.obj("prepend 0", 1, 1, 560, 195)
wtfb = w.obj("t f b", 1, 2, 700, 60, otypes=["float", "bang"])
wstop = w.msg("stop", 740, 95)
w.con(wrt, 2, wunp2, 0); w.con(wunp2, 1, wf, 1); w.con(wunp2, 0, wdel, 0); w.con(wdel, 0, wf, 0)
w.con(wf, 0, wtff, 0); w.con(wtff, 0, wpre, 0); w.con(wpre, 0, wenv, 0)
w.con(wrt, 3, wtfb, 0); w.con(wtfb, 1, wstop, 0); w.con(wstop, 0, wdel, 0); w.con(wtfb, 0, wtff, 0)
# nach dem Ausklingen: groove~ anhalten und Voice stummschalten
wplus = w.obj("+ 50.", 2, 1, 460, 195, otypes=["float"])
woff = w.obj("delay", 2, 1, 460, 225, otypes=["bang"])
wtbb = w.obj("t b b", 1, 2, 460, 255, otypes=["bang", "bang"])
wzero = w.msg("0.", 400, 285)
w.con(wtff, 1, wplus, 0); w.con(wplus, 0, woff, 0); w.con(wstop_off, 0, woff, 0)
w.con(woff, 0, wtbb, 0)
w.con(wtbb, 1, wzero, 0); w.con(wzero, 0, wsig, 0)
w.con(wtbb, 0, wmute1, 0)

wm1 = w.obj("*~", 2, 1, 200, 370, otypes=["signal"])
wm2 = w.obj("*~", 2, 1, 270, 370, otypes=["signal"])
wo1 = w.obj("out~ 1", 1, 0, 200, 410)
wo2 = w.obj("out~ 2", 1, 0, 270, 410)
w.con(wgroove, 0, wm1, 0); w.con(wgroove, 1, wm2, 0)
w.con(wenv, 0, wm1, 1); w.con(wenv, 0, wm2, 1)
w.con(wm1, 0, wo1, 0); w.con(wm2, 0, wo2, 0)
json.dump(w.to_json([100, 100, 900, 480]), open("ytwarpvoice.maxpat", "w"), indent=1, ensure_ascii=False)
